export const en = {
  'app.name': 'Kingdom of Choices',
};

const dictionaries = { fa, en };
let currentLang = 'fa';

export function setLanguage(lang) {
  if (dictionaries[lang]) currentLang = lang;
}

export function t(key, params) {
  let s = (dictionaries[currentLang] && dictionaries[currentLang][key]) ?? dictionaries.fa[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}
